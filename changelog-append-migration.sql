## Migration (run before deploying)

`changelog-migration.sql` creates the `changelog_entries` table (idempotent),
its indexes, an `updated_at` trigger, and an admin/assistant RLS **read**
policy. Writes go through the service-role key in the API routes, so there is no
client write policy. The first time it runs (only when the table is empty) it
**seeds 26 entries generated from the project's own `aminocan/changelogs/`
write-ups**, so the timeline ships pre-filled with real history instead of a
blank slate.

The seed block is generated by `scripts/gen-changelog-seed.mjs` — a
dependency-free Node script that reads each markdown write-up, extracts the
title/summary/body, attaches curated category/impact/tags/affected-areas, and
emits the rows using Postgres dollar-quoting (`$cl$…$cl$`) so arbitrary markdown
needs no escaping. Re-run it after editing the write-ups; don't hand-edit the
generated seed:

```
cd aminocan && node scripts/gen-changelog-seed.mjs
```

Columns: `category`, `title`, `summary`, `body` (markdown), `author`, `version`,
`impact` (`critical|major|minor`), `tags[]`, `affected_areas[]`, `links` (jsonb
`[{label,url}]`), `entry_date` (the timestamp the entry is grouped/dated by —
editable so entries can be backdated), `created_by`, timestamps.

### Category re-categorization patch

The seeded entries were initially all categorized `feature`/`ui`/`bugfix`/
`security`, which left the **Admin** and **Storefront** category filters empty
(that context lived in `affected_areas`, not `category`). The seed was re-mapped
to a useful spread — **admin 11, storefront 7, ui 3, feature 3, bugfix 1,
security 1**.

Because the base seed only fills an empty table (`WHERE NOT EXISTS`), it can't
fix rows that were already inserted. `changelog-recategorize-migration.sql`
patches existing databases with idempotent `UPDATE`s matched by title + author
(`Engineering`), so hand-authored entries are never touched. Fresh installs get
the correct categories from `changelog-migration.sql` and don't need the patch.
Both SQL files are generated by `scripts/gen-changelog-seed.mjs`.

